#!/usr/bin/env python3
"""Generate modules/fastjson_pow5_128.h — the 128-bit truncated powers of five
used by the Eisel–Lemire decimal→binary64 conversion in fastjson_turbo.

Entry k (k = q - (-342)) holds 5^q normalised so that bit 127 is set, as two
uint64 words (high, low). For q < 0 the reciprocal is rounded up (+1) so the
product is never under-estimated; for q >= 0 the value is truncated. This is
the same table construction used by fast_float / simdjson (Lemire, "Number
Parsing at a Gigabyte per Second", SPE 2021).

Usage: python3 tools/gen_pow5_table.py > modules/fastjson_pow5_128.h
"""

SMALLEST_Q = -342
LARGEST_Q = 308


def entries():
    out = []
    for q in range(SMALLEST_Q, 0):
        power5 = 5 ** -q
        z = 0
        while (1 << z) < power5:
            z += 1
        if q >= -27:
            b = z + 127
            c = 2 ** b // power5 + 1
        else:
            b = 2 * z + 2 * 64
            c = 2 ** b // power5 + 1
            while c >= (1 << 128):
                c //= 2
        out.append((q, c))
    for q in range(0, LARGEST_Q + 1):
        power5 = 5 ** q
        while power5 < (1 << 127):
            power5 *= 2
        while power5 >= (1 << 128):
            power5 //= 2
        out.append((q, power5))
    return out


def main():
    rows = entries()
    assert len(rows) == LARGEST_Q - SMALLEST_Q + 1
    print("// GENERATED by tools/gen_pow5_table.py — do not edit by hand.")
    print("// 128-bit normalised powers of five, 5^q for q in [-342, 308],")
    print("// stored as {high64, low64} pairs (Eisel–Lemire table).")
    print("#pragma once")
    print("#include <cstdint>")
    print("")
    print("namespace fastjson_turbo_tables {")
    print(f"inline constexpr int pow5_smallest_q = {SMALLEST_Q};")
    print(f"inline constexpr int pow5_largest_q  = {LARGEST_Q};")
    print(f"inline constexpr std::uint64_t pow5_128[{2 * len(rows)}] = {{")
    for q, c in rows:
        hi = c >> 64
        lo = c & ((1 << 64) - 1)
        assert hi >> 63 == 1, q
        print(f"    0x{hi:016x}ULL, 0x{lo:016x}ULL,  // 5^{q}")
    print("};")
    print("}  // namespace fastjson_turbo_tables")


if __name__ == "__main__":
    main()
